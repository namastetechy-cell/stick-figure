"""words.json -> engine/src/videos/arms/words.ts (+ captions.srt). Run after editing timings."""
import json, sys
w = json.load(open(sys.argv[1]))
rows = ",\n".join(f'  [{json.dumps(x["w"])}, {x["s"]}, {x["e"]}, {x["line"]}]' for x in w)
open(sys.argv[2], "w").write("// Generated by shorts/ten-arms/make_words_ts.py from words.json: [word, start s, end s, line]\n"
                             f"export const WORDS: [string, number, number, number][] = [\n{rows},\n];\n")
